"""Generate a daily VFX status briefing.

    python -m production_assistant sample_data/shots.csv --vendors sample_data/vendors.csv
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

from shot_validator.models import load_shots, load_vendors

from .assistant import generate_briefing, render_prompts
from .context import build_context
from .providers import get_provider


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="production_assistant", description=__doc__.splitlines()[0])
    p.add_argument("shots", type=Path)
    p.add_argument("--vendors", type=Path, required=True)
    p.add_argument("--show-name", default="Nova Drift")
    p.add_argument("--as-of", type=date.fromisoformat, default=date.today())
    p.add_argument("--provider", choices=["auto", "openai", "anthropic", "offline"], default="auto",
                   help="auto = OpenAI if OPENAI_API_KEY is set, else Anthropic if ANTHROPIC_API_KEY, else offline")
    p.add_argument("--dump-context", action="store_true", help="print the JSON sent to the model and exit")
    p.add_argument("--dump-prompt", action="store_true", help="print the full prompt and exit")
    p.add_argument("-o", "--output", type=Path)
    args = p.parse_args(argv)

    context = build_context(load_shots(args.shots), load_vendors(args.vendors), args.as_of, args.show_name)
    if args.dump_context:
        print(json.dumps(context, indent=2))
        return 0
    if args.dump_prompt:
        system, user = render_prompts(context)
        print(f"--- SYSTEM ---\n{system}\n--- USER ---\n{user}")
        return 0

    briefing = generate_briefing(context, get_provider(args.provider))
    header = f"<!-- generated by production_assistant | provider={briefing.provider} | as_of={args.as_of} -->\n"
    text = header + f"# {args.show_name} VFX Briefing ({args.as_of})\n\n" + briefing.markdown

    if args.output:
        args.output.write_text(text, encoding="utf-8")
        print(f"Wrote briefing to {args.output} (provider: {briefing.provider})")
    else:
        print(text)

    if not briefing.passed_guardrails:
        print(f"GUARDRAIL: model mentioned shots not in the data: {', '.join(briefing.unknown_shots)}",
              file=sys.stderr)
        return 2
    return 0
